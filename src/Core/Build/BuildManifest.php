<?php

declare(strict_types=1);

namespace Trilobit\Core\Build;

use Nette\Utils\FileSystem;
use Trilobit\Core\Module\Module;
use Trilobit\Core\Module\ModuleList;

/**
 * What a build writes down about itself, for the tools that cannot ask the
 * container.
 *
 * PHP finds out which modules are on by compiling a container. The asset
 * bundler and the stylesheet cannot do that, and they have to know: a bundle
 * built from every module's sources would ship code for modules this
 * installation does not have, and a stylesheet scanning every module's
 * templates would ship their classes too.
 *
 * The two files are generated rather than committed. A committed copy is a
 * second source of truth, and it goes stale the first time somebody switches a
 * module off - which is precisely the moment it matters.
 */
final readonly class BuildManifest
{
    /** Under the root, and inside var/, which is generated and not in the repository. */
    public const string DIRECTORY = 'var/build';

    /** Which modules this build is made of, for whatever reads JSON. */
    public const string MODULES_FILE = 'modules.json';

    /** Where the stylesheet build should look for class names, for whatever reads CSS. */
    public const string SOURCES_FILE = 'sources.css';

    public function __construct(
        private ModuleList $modules,
    ) {}

    public function directory(): string
    {
        return $this->modules->rootDirectory() . '/' . self::DIRECTORY;
    }

    public function modulesJson(): string
    {
        $modules = array_map(
            static fn(Module $module): array => [
                'name' => $module->name,
                'namespace' => $module->namespace(),
                'directory' => $module->relativeDirectory(),
            ],
            $this->modules->enabled(),
        );

        return json_encode(
            ['modules' => $modules],
            JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR,
        ) . "\n";
    }

    /**
     * Core is always here and the enabled modules follow it. The paths are
     * relative to the file itself, because that is how the stylesheet build
     * resolves them, and the file's own location is fixed two levels under the
     * root.
     */
    public function sourcesCss(): string
    {
        $directories = ['src/Core'];
        foreach ($this->modules->enabled() as $module) {
            $directories[] = $module->relativeDirectory();
        }

        $lines = array_map(
            static fn(string $directory): string => sprintf('@source "../../%s";', $directory),
            $directories,
        );

        return "/* Generated by `bin/trilobit app:warmup`. Changes here are overwritten. */\n"
            . implode("\n", $lines) . "\n";
    }

    /**
     * @return list<string> the files written, in the order they were written
     */
    public function write(): array
    {
        $directory = $this->directory();

        FileSystem::write($directory . '/' . self::MODULES_FILE, $this->modulesJson());
        FileSystem::write($directory . '/' . self::SOURCES_FILE, $this->sourcesCss());

        return [
            $directory . '/' . self::MODULES_FILE,
            $directory . '/' . self::SOURCES_FILE,
        ];
    }
}
